print("4. BUILT-IN SET FUNCTIONS")
nums = {10, 20, 5, 30}
print("len():", len(nums))
print("max():", max(nums))
print("min():", min(nums))
print("sum():", sum(nums))
print("sorted():", sorted(nums))
print("set('hello'):", set("hello"))
print("any({0,1}):", any({0, 1}))
print("all({1,2,3}):", all({1, 2, 3}))

