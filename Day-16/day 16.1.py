print("3. SET OPERATIONS")
a = {1, 2, 3}
b = {3, 4, 5}
print("Membership 20 in data:", 20 in {10, 20, 30})
print("Union (a | b):", a | b)
print("Intersection (a & b):", a & b)
print("Difference (a - b):", a - b)
print("Symmetric Difference (a ^ b):", a ^ b)
print("Subset (a <= b):", {1, 2} <= {1, 2, 3, 4})
print("Superset (a >= b):", {1, 2, 3, 4} >= {1, 2})
