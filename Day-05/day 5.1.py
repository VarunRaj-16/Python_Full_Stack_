#2. Assignment Operators
# Simple assignment
a = 10

# +=
a = 100
a += 500
print(a)                    # 600   (same as a = a + 500)

# Real-time: Wallet Balance
wallet = 1000
wallet += 500
print(wallet)               # 1500

# -=
a = 600
a -= 200
print(a)                    # 400

# Real-time: Electricity Bill
balance = 5000
bill = 1500
balance -= bill
print(balance)              # 3500
