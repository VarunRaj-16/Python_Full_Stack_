import numpy as np
# 1. CREATING NUMPY ARRAYS
# 1D array
arr1 = np.array([1, 2, 3, 4, 5])
print(arr1)
# 2D array
arr2 = np.array([[1, 2, 3], [4, 5, 6]])
print(arr2)
# 3D array
arr3 = np.array([[[1, 2], [3, 4]], [[5, 6], [7, 8]]])
print(arr3)
# Array of zeros
zeros = np.zeros((3, 3))
print(zeros)
# Array of ones
ones = np.ones((2, 4))
print(ones)
