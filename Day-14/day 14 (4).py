print("6. FOUR COMBINATIONS OF FUNCTIONS")# Type 1: No Arguments, No Return
def Welcome():
    print("Welcome to ABC Bank")
Welcome()# Type 2: With Arguments, No Return
def Welcome_User(name):
    print("Welcome", name)
Welcome_User("Raju")# Type 3: No Arguments, With Return
def GetCountry():
    return "India"
print(GetCountry())# Type 4: With Arguments, With Return
def Add(a, b):
    return a + b
print(Add(10, 20))

